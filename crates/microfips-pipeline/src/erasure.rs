//! PRBS23-XOR erasure coding — no_std Rust port.
//!
//! Provenance: ported from balloon-fresh `tracker/firmware/components/erasure/erasure.c`
//! (see `docs/pipeline-provenance.md`). The C original is the reference
//! implementation; the constants and the PRBS23 LFSR are reproduced verbatim so
//! that a balloon-fresh transmitter and a microfips receiver interoperate on the
//! same parity blocks.
//!
//! # Algorithm
//!
//! The message is split into `k` equal-size fragments (`frag_nb`). A parity
//! ("redundancy") fragment `r` (1-based) is the XOR of the original fragments
//! selected by bit `i` of row `r` of a pseudo-random binary matrix generated by
//! a PRBS23 LFSR. Each row has exactly `k/2` bits set.
//!
//! Decoding is incremental:
//!   1. Originals are copied straight into the assembly buffer.
//!   2. A parity row containing exactly one still-missing original solves that
//!      original directly (XOR out the received ones).
//!   3. Once enough independent parity rows accumulate (>= number missing),
//!      Gaussian elimination over GF(2) solves the remaining set.
//!
//! Failure semantics are the C code's, deliberately: an unusable fragment is
//! reported as an error status and never panics. On a `no_std` leaf node a
//! malformed radio fragment must be a cheap drop, never a fault.

/// Maximum number of original fragments in one block.
pub const MAX_FRAGS: usize = 64;
/// Maximum number of redundancy fragments per block.
pub const MAX_REDUNDANCY: usize = 32;
/// Maximum size of a single fragment payload, in bytes.
pub const MAX_FRAG_SIZE: usize = 242;

/// Number of bytes in one parity-matrix row over `frag_nb` columns.
const fn matrix_row_bytes(frag_nb: usize) -> usize {
    (frag_nb >> 3) + 1
}

/// Outcome of feeding one fragment to the decoder.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum DecodeStatus {
    /// Every original fragment is now present; the assembly buffer is complete.
    Complete,
    /// The fragment was absorbed; more fragments are still needed.
    Progress,
    /// The fragment index was out of range, or the fragment was unusable.
    Invalid,
}

/// PRBS23: a 23-bit pseudo-random binary sequence stepper.
///
/// Faithful to the C original, including the arithmetic-shift semantics: the
/// value is treated as a 23-bit register, so the caller must keep it in range.
#[inline]
pub fn prbs23(value: i32) -> i32 {
    let b0 = value & 0x01;
    let b1 = (value & 0x20) >> 5;
    (value >> 1) + ((b0 ^ b1) << 22)
}

/// Generate row `n` of the parity matrix into `matrix_row`.
///
/// Row `n` has exactly `m/2` bits set. The LFSR is seeded with `1 + 1001*n` so
/// every row is a distinct stream; the `m_temp` adjustment avoids a degenerate
/// all-zero row when `m` is a power of two.
fn get_parity_matrix_row(n: i32, m: i32, matrix_row: &mut [u8]) {
    let m_temp = if (m & (m - 1)) == 0 { 1 } else { 0 };

    let mut x = 1 + (1001 * n);
    let row_size = matrix_row_bytes(m as usize);

    for b in matrix_row[..row_size].iter_mut() {
        *b = 0;
    }

    let mut nb_coeff = 0;
    while nb_coeff < (m >> 1) {
        let mut r = 1 << 16;
        while r >= m {
            x = prbs23(x);
            r = x % (m + m_temp);
        }
        matrix_row[(r >> 3) as usize] |= 1 << (r & 7);
        nb_coeff += 1;
    }
}

/// Read bit `index` out of a packed parity-matrix row.
#[inline]
fn get_parity(index: usize, matrix_row: &[u8]) -> bool {
    (matrix_row[index >> 3] >> (index & 7)) & 1 == 1
}

/// The set of column indices set in parity row `n` for `m` originals.
///
/// Exposed for diagnostics: the codec's effective strength is bounded by these
/// rows' actual weights and mutual independence, not by its nominal parameters.
/// See `examples/matrix_rank.rs`.
pub fn parity_row_bits(n: i32, m: i32) -> alloc::vec::Vec<usize> {
    let mut row = [0u8; (MAX_FRAGS >> 3) + 1];
    get_parity_matrix_row(n, m, &mut row);
    let mut out = alloc::vec::Vec::new();
    for i in 0..m as usize {
        if get_parity(i, &row) {
            out.push(i);
        }
    }
    out
}

/// `dst ^= src`, byte-wise.
#[inline]
fn xor_line(dst: &mut [u8], src: &[u8], size: usize) {
    for i in 0..size {
        dst[i] ^= src[i];
    }
}

/// Add `candidate` to the row-echelon basis `a` (which holds `accepted` rows of
/// `row_bytes` bytes each), reducing it against the existing rows.
///
/// Returns `Some(new_accepted)` when the candidate is linearly independent —
/// it is written to row `accepted` and the count grows by one — or `None` when
/// it reduces to zero (linearly dependent, adds no information).
///
/// The basis is kept in row-echelon form: each accepted row's leading
/// (lowest-index) set bit is stored in `pivots[row]`.
///
/// Reduction XORs *whole* rows rather than only the tail from the pivot byte.
/// The tail-only optimisation is valid only when the basis is in *reduced*
/// echelon form (each pivot column clear in every other row); rows here are
/// accepted in arrival order, so an earlier pivot's XOR can reintroduce bits
/// at a later pivot and a single sweep would then mis-classify independent
/// rows as dependent. Sweeping to a fixed point avoids that.
fn echelon_insert(
    a: &mut [u8],
    pivots: &mut [usize],
    accepted: usize,
    candidate: &[u8],
    row_bytes: usize,
    mut reduce_rhs: impl FnMut(usize),
) -> Option<usize> {
    let mut work = [0u8; MAX_FRAGS / 8 + 1];
    work[..row_bytes].copy_from_slice(&candidate[..row_bytes]);

    // Clear the candidate's bit at each existing pivot column, lowest pivot
    // first. Each basis row is stored in *row-echelon* form: its leading set
    // bit is `pivots[row]`. Pivots are NOT in acceptance order (the leading bit
    // of the reduced candidate can be lower than a pivot accepted earlier), so
    // sort by pivot column and eliminate strictly lowest-first: XORing a row
    // whose pivot is HIGHER than the bit being cleared would set a bit above
    // the current leading position and can cancel bits a later row depends on,
    // which reduces an independent row to zero. Measured on the max geometry
    // (k=32 projected onto 16 missing): the unsorted sweep reported
    // `valid_rows=15 < n=16` although an independent GF(2) rank computation
    // gives 16, and the block never decoded.
    let mut order = [0usize; MAX_FRAGS];
    for (slot, ord) in order.iter_mut().enumerate().take(accepted) {
        *ord = slot;
    }
    order[..accepted].sort_unstable_by_key(|&r| pivots[r]);

    for &row in order[..accepted].iter() {
        let pivot_col = pivots[row];
        if pivot_col == usize::MAX {
            continue;
        }
        if (work[pivot_col >> 3] >> (pivot_col & 7)) & 1 == 1 {
            let row_base = row * row_bytes;
            for byte in 0..row_bytes {
                work[byte] ^= a[row_base + byte];
            }
            // Every XOR applied to the coefficient row must be applied to its
            // right-hand side too, or the stored system pairs a reduced matrix
            // row with an unreduced data row and the solve silently produces
            // garbage (while still reporting complete).
            reduce_rhs(row);
        }
    }

    // Leading bit of what is left becomes this row's pivot.
    let mut pivot_col = usize::MAX;
    'scan: for byte in 0..row_bytes {
        if work[byte] != 0 {
            for bit in 0..8 {
                if (work[byte] >> bit) & 1 == 1 {
                    pivot_col = byte * 8 + bit;
                    break 'scan;
                }
            }
        }
    }
    if pivot_col == usize::MAX {
        return None;
    }

    let dst = accepted * row_bytes;
    a[dst..dst + row_bytes].copy_from_slice(&work[..row_bytes]);
    pivots[accepted] = pivot_col;
    Some(accepted + 1)
}

/// Encode redundancy: `ErasureEncoder::new(k, block_size)` in the C API.
///
/// Borrows the caller's block buffer (`k * frag_size` bytes) rather than owning
/// it, so a leaf node can encode straight out of its transmit buffer.
pub struct ErasureEncoder<'a> {
    frag_nb: usize,
    frag_size: usize,
    data: &'a [u8],
}

impl<'a> ErasureEncoder<'a> {
    /// Create an encoder over `data`, which must hold at least
    /// `frag_nb * frag_size` bytes.
    ///
    /// Returns `None` if the geometry is out of range or `data` is too short.
    pub fn new(frag_nb: usize, frag_size: usize, data: &'a [u8]) -> Option<Self> {
        if frag_nb == 0 || frag_nb > MAX_FRAGS || frag_size == 0 || frag_size > MAX_FRAG_SIZE {
            return None;
        }
        if data.len() < frag_nb * frag_size {
            return None;
        }
        Some(Self {
            frag_nb,
            frag_size,
            data,
        })
    }

    pub fn frag_nb(&self) -> usize {
        self.frag_nb
    }

    pub fn frag_size(&self) -> usize {
        self.frag_size
    }

    /// Produce redundancy fragment `redundancy_index` (0-based, must be
    /// `< MAX_REDUNDANCY`) into `out`, which must be at least `frag_size` long.
    ///
    /// The C API takes a 1-based index; the `+ 1` here preserves that.
    pub fn encode_redundant(&self, redundancy_index: usize, out: &mut [u8]) -> bool {
        if redundancy_index >= MAX_REDUNDANCY || out.len() < self.frag_size {
            return false;
        }

        let mut matrix_row = [0u8; (MAX_FRAGS >> 3) + 1];
        get_parity_matrix_row(
            redundancy_index as i32 + 1,
            self.frag_nb as i32,
            &mut matrix_row,
        );

        for b in out[..self.frag_size].iter_mut() {
            *b = 0;
        }
        for i in 0..self.frag_nb {
            if get_parity(i, &matrix_row) {
                let off = i * self.frag_size;
                xor_line(out, &self.data[off..], self.frag_size);
            }
        }
        true
    }
}

/// Decode: `ErasureDecoder::new(k, block_size)` in the C API.
///
/// Holds two caller-provided scratch buffers (assembly + pending parity rows)
/// so the struct itself stays small and can live in a `static` on a leaf node.
pub struct ErasureDecoder<'a> {
    frag_nb: usize,
    frag_size: usize,
    /// Originals at `i * frag_size`, then pending parity data starting at
    /// `frag_nb * frag_size`.
    assembly_buf: &'a mut [u8],
    /// Rows of the pending-parity matrix, `matrix_row_bytes(frag_nb)` each.
    matrix_m2b: &'a mut [u8],
    m2b_rows: usize,
    frag_nb_lost: usize,
    /// `MISSING` marks a slot that has been received; otherwise the frag index.
    frag_nb_missing: [u16; MAX_FRAGS],
    frags_received: usize,
    complete: bool,
    /// Index into the RX pool this decoder's buffers came from; the pipeline
    /// uses it to recycle the scratch buffers when a block finishes.
    pool_slot: usize,
}

/// Sentinel in `frag_nb_missing` for "this fragment is no longer missing".
const MISSING: u16 = 0xFFFF;

impl<'a> ErasureDecoder<'a> {
    /// `assembly_buf` must hold `frag_nb * frag_size + MAX_REDUNDANCY * frag_size`
    /// bytes; `matrix_buf` must hold `MAX_REDUNDANCY * matrix_row_bytes(frag_nb)`.
    pub fn new(
        frag_nb: usize,
        frag_size: usize,
        assembly_buf: &'a mut [u8],
        matrix_buf: &'a mut [u8],
    ) -> Option<Self> {
        if frag_nb == 0 || frag_nb > MAX_FRAGS || frag_size == 0 || frag_size > MAX_FRAG_SIZE {
            return None;
        }
        let assembly_needed = frag_nb * frag_size + MAX_REDUNDANCY * frag_size;
        let matrix_needed = MAX_REDUNDANCY * matrix_row_bytes(frag_nb);
        if assembly_buf.len() < assembly_needed || matrix_buf.len() < matrix_needed {
            return None;
        }

        for b in assembly_buf[..frag_nb * frag_size].iter_mut() {
            *b = 0;
        }
        for b in matrix_buf[..matrix_needed].iter_mut() {
            *b = 0;
        }

        let mut dec = Self {
            frag_nb,
            frag_size,
            assembly_buf,
            matrix_m2b: matrix_buf,
            m2b_rows: 0,
            frag_nb_lost: frag_nb,
            frag_nb_missing: [MISSING; MAX_FRAGS],
            frags_received: 0,
            complete: false,
            pool_slot: 0,
        };
        for i in 0..frag_nb {
            dec.frag_nb_missing[i] = i as u16;
        }
        Some(dec)
    }

    /// Locate `frag_index` in the missing list, if it is still missing.
    fn find_missing_index(&self, frag_index: usize) -> Option<usize> {
        for i in 0..self.frag_nb {
            if self.frag_nb_missing[i] as usize == frag_index {
                return Some(i);
            }
        }
        None
    }

    /// Mark `frag_index` received (by frag index, not slot index).
    fn mark_received(&mut self, frag_index: usize) -> bool {
        for i in 0..self.frag_nb {
            if self.frag_nb_missing[i] as usize == frag_index {
                self.frag_nb_missing[i] = MISSING;
                self.frag_nb_lost -= 1;
                return true;
            }
        }
        false
    }

    /// Where original fragment `i` lives in the assembly buffer.
    #[inline]
    fn original_offset(&self, i: usize) -> usize {
        i * self.frag_size
    }

    /// Where pending-parity row `row` lives in the assembly buffer.
    #[inline]
    fn pending_parity_offset(&self, row: usize) -> usize {
        self.frag_nb * self.frag_size + row * self.frag_size
    }

    /// Gaussian elimination over GF(2) across the accumulated parity rows.
    fn ge_solve(&mut self) {
        let mut missing_indices = [0usize; MAX_FRAGS];
        let mut num_missing = 0;
        for i in 0..self.frag_nb {
            if self.frag_nb_missing[i] != MISSING {
                missing_indices[num_missing] = i;
                num_missing += 1;
            }
        }

        if num_missing == 0 {
            self.complete = true;
            return;
        }
        // Not enough independent equations yet.
        if self.m2b_rows < num_missing {
            return;
        }

        if crate::ge_trace_enabled() {
            extern crate std;
            std::eprintln!(
                "ge_solve: m2b_rows={} num_missing={} missing={:?}",
                self.m2b_rows,
                num_missing,
                &missing_indices[..num_missing]
            );
        }

        let n = num_missing;
        let row_bytes = matrix_row_bytes(n);

        // A: n x n coefficient matrix over GF(2); B: n x frag_size data.
        //
        // `row_bytes` is derived from `n` (the live missing count), and `a`
        // holds `n` such rows -- so the array must be sized for the *maximum*
        // possible `n`, i.e. `MAX_FRAGS` columns. Sizing it as
        // `MAX_FRAGS * MAX_FRAGS / 8` (= 512 B) is short: at n = 64,
        // `row_bytes = (64 >> 3) + 1 = 9` and `n * row_bytes = 576 > 512`,
        // which walks off the end of the array. Use the same `matrix_row_bytes`
        // helper the rest of the codec uses so the two can never disagree.
        const A_ROW_BYTES: usize = matrix_row_bytes(MAX_FRAGS);
        let mut a = [0u8; MAX_FRAGS * A_ROW_BYTES];
        let mut b = [0u8; MAX_FRAGS * MAX_FRAG_SIZE];

        for x in a[..n * row_bytes].iter_mut() {
            *x = 0;
        }
        for x in b[..n * self.frag_size].iter_mut() {
            *x = 0;
        }

        // Build the projected system, keeping every equation that still has at
        // least one unknown. Rows arrive in queue order, which is arrival order
        // of the parity fragments.
        //
        // NOTE ON THE C ORIGINAL: erasure.c requires `valid_rows >= n` counting
        // rows *prefix-wise* and bails otherwise, then runs elimination without
        // a rank check. Two consequences, both observed on the reference C
        // (tools/c_ref_check.c): (a) an equation that is linearly dependent on
        // earlier ones still consumes one of the n slots, so the matrix can be
        // singular and the whole solve is abandoned even though enough
        // independent equations arrived; (b) rows are only ever *appended*
        // projected at insertion time, so solving some originals can strand
        // later rows. This port fixes both by selecting rows by rank and
        // re-projecting against the live missing set on every attempt.
        let src_row_bytes = matrix_row_bytes(self.frag_nb);
        let mut valid_rows = 0;
        let mut pivots = [usize::MAX; MAX_FRAGS];
        for row in 0..self.m2b_rows {
            if valid_rows >= n {
                break;
            }
            let src_off = row * src_row_bytes;
            let src = &self.matrix_m2b[src_off..src_off + src_row_bytes];
            let data_off = self.pending_parity_offset(row);

            // Project the row onto the missing columns.
            let mut projected = [0u8; MAX_FRAGS / 8 + 1];
            let mut covered = [0usize; MAX_FRAGS];
            let mut ncovered = 0;
            for col in 0..n {
                if get_parity(missing_indices[col], src) {
                    projected[col >> 3] |= 1 << (col & 7);
                    covered[ncovered] = col;
                    ncovered += 1;
                }
            }
            if crate::ge_trace_enabled() {
                extern crate std;
                std::eprintln!(
                    "  ge row={row} covers {:?} of missing {:?}",
                    &covered[..ncovered],
                    &missing_indices[..n]
                );
                std::eprintln!("    raw bits {:?}", &src[..src_row_bytes]);
            }

            // RHS: the raw payload minus every *already-known* original in the
            // row, so the system is expressed purely in the unknown columns.
            let mut rhs = [0u8; MAX_FRAG_SIZE];
            let src_data = &self.assembly_buf[data_off..data_off + self.frag_size];
            rhs[..self.frag_size].copy_from_slice(src_data);
            for known in 0..self.frag_nb {
                if !get_parity(known, src) {
                    continue;
                }
                if self.find_missing_index(known).is_some() {
                    continue;
                }
                let off = self.original_offset(known);
                let mut cur = [0u8; MAX_FRAG_SIZE];
                cur[..self.frag_size]
                    .copy_from_slice(&self.assembly_buf[off..off + self.frag_size]);
                xor_line(&mut rhs, &cur, self.frag_size);
            }

            // Accept the row only if it is linearly independent of the ones
            // already taken; dependent rows carry no new information and would
            // make the system singular. The same row operations that reduce the
            // coefficient row must reduce its RHS: `rhs_red` accumulates those
            // XORs, is copied into slot `valid_rows` on acceptance, and is
            // discarded on rejection. (Reducing into `b[valid_rows]` directly
            // would XOR against whatever the slot last held.)
            let mut rhs_red = rhs;
            let (a_ref, b_ref) = (&mut a, &b);
            let fs = self.frag_size;
            match echelon_insert(
                a_ref,
                &mut pivots,
                valid_rows,
                &projected[..row_bytes],
                row_bytes,
                |src_row| {
                    let s = src_row * fs;
                    for k in 0..fs {
                        rhs_red[k] ^= b_ref[s + k];
                    }
                },
            ) {
                Some(next) => {
                    let b_off = valid_rows * self.frag_size;
                    b[b_off..b_off + self.frag_size].copy_from_slice(&rhs_red[..self.frag_size]);
                    valid_rows = next;
                }
                None => continue,
            }
        }

        if valid_rows < n {
            if crate::ge_trace_enabled() {
                extern crate std;
                std::eprintln!("  ge: BAIL valid_rows={valid_rows} < n={n}");
            }
            return;
        }

        // Reduce to reduced row-echelon form, applying each row operation to B
        // too.
        //
        // The row `i` accepted by `echelon_insert` pivots on column
        // `pivots[i]`, which is NOT necessarily column `i`: `echelon_insert`
        // picks the leading set bit of the reduced candidate, and rows arrive
        // in arbitrary order. Driving this loop off the diagonal assumption
        // (`get_parity(pivot, row)` with `pivot == column`) both mis-detects
        // singular systems and, worse, *succeeds* on a matrix whose rows are
        // not in the expected positions -- writing out rows that are still
        // linear combinations of several unknowns as if each were solved.
        // That is the wrong-reconstruction-with-complete=true defect.
        // Eliminate on `pivots[]` instead.
        for pivot_row in 0..n {
            let prow_base = pivot_row * row_bytes;
            let pivot_col = pivots[pivot_row];
            if pivot_col == usize::MAX {
                // Unreachable once `valid_rows >= n`, but keep the solver
                // honest: an unknown pivot means the system is not solvable.
                return;
            }
            // Normalise this row to unit pivot: no other row may have a bit at
            // `pivot_col`. `echelon_insert` already reduced each accepted row
            // against the *earlier* pivots, so forward elimination below is
            // sufficient, but sweeping all rows keeps the invariant explicit.
            if !get_parity(pivot_col, &a[prow_base..prow_base + row_bytes]) {
                return;
            }

            for elim in 0..n {
                if elim == pivot_row {
                    continue;
                }
                let erow_base = elim * row_bytes;
                if get_parity(pivot_col, &a[erow_base..erow_base + row_bytes]) {
                    for b_ in 0..row_bytes {
                        a[erow_base + b_] ^= a[prow_base + b_];
                    }
                    let pdata = pivot_row * self.frag_size;
                    let edata = elim * self.frag_size;
                    // Split the borrow across the two disjoint data rows.
                    if edata < pdata {
                        let (lo, hi) = b.split_at_mut(pdata);
                        xor_line(
                            &mut lo[edata..edata + self.frag_size],
                            &hi[..self.frag_size],
                            self.frag_size,
                        );
                    } else {
                        let (lo, hi) = b.split_at_mut(edata);
                        xor_line(
                            &mut hi[..self.frag_size],
                            &lo[pdata..pdata + self.frag_size],
                            self.frag_size,
                        );
                    }
                }
            }
        }

        // Write solved originals back into place.
        //
        // After full reduction, row `pivot_row` holds the unit vector for
        // column `pivots[pivot_row]`, i.e. its RHS is the value of
        // `missing_indices[pivots[pivot_row]]` -- the mapping is via the pivot
        // column, not the row ordinal.
        for pivot_row in 0..n {
            let pivot_col = pivots[pivot_row];
            if pivot_col == usize::MAX {
                continue;
            }
            let off = self.original_offset(missing_indices[pivot_col]);
            let src = pivot_row * self.frag_size;
            // `missing_indices` and the solved rows refer to disjoint memory
            // only in the general case; copy through a small stack buffer.
            let mut tmp = [0u8; MAX_FRAG_SIZE];
            tmp[..self.frag_size].copy_from_slice(&b[src..src + self.frag_size]);
            self.assembly_buf[off..off + self.frag_size]
                .copy_from_slice(&tmp[..self.frag_size]);
            self.mark_received(missing_indices[pivot_col]);
        }

        if self.frag_nb_lost == 0 {
            self.complete = true;
        }
    }

    /// Feed one fragment. `frag_counter` is 1-based: `1..=frag_nb` are
    /// originals, above that are redundancy fragments.
    pub fn process(&mut self, frag_counter: u16, raw_data: &[u8]) -> DecodeStatus {
        if self.complete {
            return DecodeStatus::Complete;
        }
        if raw_data.len() < self.frag_size {
            return DecodeStatus::Invalid;
        }
        let counter = frag_counter as usize;
        if counter == 0 || counter > self.frag_nb + MAX_REDUNDANCY {
            return DecodeStatus::Invalid;
        }

        if counter <= self.frag_nb {
            let off = self.original_offset(counter - 1);
            self.assembly_buf[off..off + self.frag_size]
                .copy_from_slice(&raw_data[..self.frag_size]);
            self.mark_received(counter - 1);

            if self.frag_nb_lost == 0 {
                self.complete = true;
                return DecodeStatus::Complete;
            }
            self.frags_received += 1;
            // An original arriving may be the last one a queued parity row was
            // waiting for, so try to drain the pending equations here too.
            if self.try_drain_pending() {
                return DecodeStatus::Complete;
            }
            return DecodeStatus::Progress;
        }

        let redundancy_idx = counter - self.frag_nb;

        let mut matrix_row = [0u8; (MAX_FRAGS >> 3) + 1];
        get_parity_matrix_row(
            redundancy_idx as i32,
            self.frag_nb as i32,
            &mut matrix_row,
        );

        // Store the fragment as a *permanent, full-fidelity* equation:
        //   XOR{ original[i] : row bit i set } = raw parity payload
        // Both halves are kept raw -- the row bits cover every original (not
        // just the currently-missing ones) and the payload still contains the
        // contributions of already-received originals. This is what lets the
        // same row be re-projected against a *different* missing set later, in
        // any order, which is the property the C original's append-time
        // projection destroys (see the `ge_solve` note).
        let row_bytes = matrix_row_bytes(self.frag_nb);
        if self.m2b_rows >= MAX_REDUNDANCY {
            // A block can never carry more distinct parity fragments than this.
            return DecodeStatus::Invalid;
        }
        for b in self.matrix_m2b[self.m2b_rows * row_bytes..(self.m2b_rows + 1) * row_bytes]
            .iter_mut()
        {
            *b = 0;
        }
        for i in 0..self.frag_nb {
            if get_parity(i, &matrix_row) {
                self.matrix_m2b[self.m2b_rows * row_bytes + (i >> 3)] |= 1 << (i & 7);
            }
        }

        let data_off = self.pending_parity_offset(self.m2b_rows);
        self.assembly_buf[data_off..data_off + self.frag_size]
            .copy_from_slice(&raw_data[..self.frag_size]);

        self.m2b_rows += 1;

        if crate::ge_trace_enabled() {
            extern crate std;
            std::eprintln!(
                "  parity counter={} redo_idx={} m2b_rows={} lost={}",
                counter,
                redundancy_idx,
                self.m2b_rows,
                self.frag_nb_lost
            );
        }

        // A single stored equation may already determine an original on its own
        // (after the received ones are subtracted); `try_drain_pending` covers
        // that, so no special case is needed here.
        self.frags_received += 1;

        if self.try_drain_pending() {
            return DecodeStatus::Complete;
        }

        DecodeStatus::Progress
    }

    /// Run the pending-equation solvers and report whether the block completed.
    ///
    /// Called after *any* fragment makes progress, not just parity fragments.
    /// Two solver passes are applied, in a loop, because each can unlock the
    /// other:
    ///
    /// 1. **Single-unknown pass** — a stored equation whose only remaining
    ///    unknown is one original solves it directly (subtract the known ones).
    ///    Cheap and exact; covers the common case where parity fragments arrive
    ///    one at a time.
    /// 2. **Gaussian elimination** — when enough independent equations have
    ///    accumulated, solve the whole missing set at once.
    ///
    /// The C original runs pass 2 before pass 1 and only inside the redundancy
    /// branch, which strands recoveries whenever the last originals needed to
    /// make `m2b_rows >= frag_nb_lost` true arrive after every usable parity
    /// fragment already has: the one-shot check is evaluated against a
    /// still-too-high `frag_nb_lost`, and later original arrivals never
    /// re-evaluate it. Repro: k=12, 6 parity, originals 0,4,6,9,10 plus parity#1
    /// lost — `tools/c_ref_check.c` shows the reference C failing this case.
    fn try_drain_pending(&mut self) -> bool {
        if self.complete {
            return true;
        }

        loop {
            let before = self.frag_nb_lost;

            // Pass 1: equations with exactly one unknown left.
            self.solve_single_unknown_rows();
            if self.frag_nb_lost == 0 {
                self.complete = true;
                return true;
            }

            // Pass 2: full elimination over every stored equation.
            if self.m2b_rows >= 2 {
                self.ge_solve();
                if self.complete {
                    return true;
                }
            }

            if self.frag_nb_lost == before {
                // No progress this round; nothing more can be squeezed out
                // until another fragment arrives.
                break;
            }
        }

        self.complete
    }

    /// Solve every stored equation that has exactly one unknown remaining.
    ///
    /// Because stored equations keep raw payloads, the known originals in the
    /// row are XORed out of a copy of the payload before it is written back as
    /// the missing original's value.
    fn solve_single_unknown_rows(&mut self) {
        let row_bytes = matrix_row_bytes(self.frag_nb);

        for row in 0..self.m2b_rows {
            if self.complete {
                return;
            }
            let row_off = row * row_bytes;
            let mut only_missing = usize::MAX;
            let mut count = 0usize;
            {
                let bits = &self.matrix_m2b[row_off..row_off + row_bytes];
                for i in 0..self.frag_nb {
                    if get_parity(i, bits) && self.find_missing_index(i).is_some() {
                        only_missing = i;
                        count += 1;
                    }
                }
            }
            if count != 1 || only_missing == usize::MAX {
                continue;
            }

            // Copy the raw payload, then subtract every *known* original in the
            // row; what remains is the single unknown's value.
            let mut temp = [0u8; MAX_FRAG_SIZE];
            let src_off = self.pending_parity_offset(row);
            temp[..self.frag_size]
                .copy_from_slice(&self.assembly_buf[src_off..src_off + self.frag_size]);

            let mut row_bits = [0u8; (MAX_FRAGS >> 3) + 1];
            row_bits[..row_bytes]
                .copy_from_slice(&self.matrix_m2b[row_off..row_off + row_bytes]);

            for i in 0..self.frag_nb {
                if get_parity(i, &row_bits) && self.find_missing_index(i).is_none() {
                    let off = self.original_offset(i);
                    let mut cur = [0u8; MAX_FRAG_SIZE];
                    cur[..self.frag_size]
                        .copy_from_slice(&self.assembly_buf[off..off + self.frag_size]);
                    xor_line(&mut temp, &cur, self.frag_size);
                }
            }

            let off = self.original_offset(only_missing);
            self.assembly_buf[off..off + self.frag_size]
                .copy_from_slice(&temp[..self.frag_size]);
            self.mark_received(only_missing);
        }
    }

    pub fn is_complete(&self) -> bool {
        self.complete
    }

    /// The reconstructed block, or `None` if decoding has not finished.
    pub fn assembled(&self) -> Option<&[u8]> {
        if !self.complete {
            return None;
        }
        let n = self.frag_nb * self.frag_size;
        Some(&self.assembly_buf[..n])
    }

    /// Original fragment `i`, or `None` if it has not been recovered yet.
    pub fn original(&self, i: usize) -> Option<&[u8]> {
        if i >= self.frag_nb || self.frag_nb_missing[i] != MISSING {
            return None;
        }
        let off = self.original_offset(i);
        Some(&self.assembly_buf[off..off + self.frag_size])
    }

    pub fn frags_received(&self) -> usize {
        self.frags_received
    }

    pub fn frag_nb(&self) -> usize {
        self.frag_nb
    }

    pub fn frag_size(&self) -> usize {
        self.frag_size
    }

    /// Pool slot this decoder's scratch buffers were taken from.
    pub fn pool_slot(&self) -> usize {
        self.pool_slot
    }

    /// Record which pool slot supplied this decoder's buffers.
    pub fn set_pool_slot(&mut self, slot: usize) {
        self.pool_slot = slot;
    }

    /// Consume the decoder and hand back its scratch buffers so the pipeline
    /// can recycle them for the next block.
    pub fn into_buffers(self) -> (&'a mut [u8], &'a mut [u8]) {
        (self.assembly_buf, self.matrix_m2b)
    }
}
